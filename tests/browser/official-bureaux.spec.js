import {readFile,mkdir} from 'node:fs/promises';
import {test,expect} from '@playwright/test';

test.use({serviceWorkers:'block'});

test('fiche bureau : résultats ministériels T1 distincts de la valeur communiquée et absence T2',async({page})=>{
 await page.goto('/');
 await page.locator('button[data-nav=carte]:visible').first().click();
 await page.locator('#map-scope').selectOption('bureau');
 await page.locator('#bureau-commune').selectOption('Bourg');
 await page.locator('#map-scope-value').selectOption('33067-1');
 const detail=page.locator('.map-detail .panel');
 await expect(detail).toContainText('Valeur communiquée séparément');
 await expect(detail).toContainText('875');
 const result=detail.locator('.official-bureau-result');
 await expect(result).toContainText('Législatives 2024 · 1er tour (30 juin)');
 await expect(result).toContainText('832');
 await expect(result).toContainText('530');
 await expect(result).toContainText('Edwige DIAZ');
 await expect(result).toContainText('221 voix');
 await expect(result.getByRole('link',{name:/Ministère de l’Intérieur/})).toHaveAttribute('href',/data\.gouv\.fr\/datasets/);
 await expect(result).toContainText('périmètre géographique');
 await expect(result).toContainText('scrutin non tenu');
 await expect(result.locator('.bureau-vote-scale')).toContainText('513 suffrages exprimés');
 const shares=await result.locator('.bureau-vote-track i').evaluateAll(nodes=>nodes.map(node=>parseFloat(node.style.width)));
 expect(shares[0]).toBeCloseTo(160*100/513,4);
 expect(shares[1]).toBeCloseTo(221*100/513,4);
 await page.locator('#map-scope-value').selectOption('33067-2');
 await expect(result.locator('.bureau-vote-scale')).toContainText('564 suffrages exprimés');
 await expect(result.locator('.official-bureau-candidates li').first()).toContainText('147 voix');
 const secondShares=await result.locator('.bureau-vote-track i').evaluateAll(nodes=>nodes.map(node=>parseFloat(node.style.width)));
 expect(secondShares[0]).toBeCloseTo(147*100/564,4);
 await page.locator('#bureau-commune').selectOption('Cavignac');
 await page.locator('#map-scope-value').selectOption('33114-2');
 const missing=page.locator('.map-detail .official-bureau-result');
 await expect(missing).toContainText('Aucun résultat officiel apparié');
 await expect(missing).toContainText('un seul bureau');
 await expect(missing.locator('.official-bureau-candidates')).toHaveCount(0);
});

test('comparaison de bureaux sourcée sur ordinateur et mobile émulé',async({page},testInfo)=>{
 test.skip(!['desktop','iphone'].includes(testInfo.project.name));
 await page.goto('/');
 await page.locator('button[data-nav=carte]:visible').first().click();
 await page.locator('#map-scope').selectOption('bureau');
 await page.locator('#bureau-commune').selectOption('Bourg');
 await page.locator('#map-scope-value').selectOption('33067-1');
 await page.locator('#bureau-comparison-b').selectOption('33067-2');
 const comparison=page.locator('.official-bureau-comparison');
 await expect(comparison).toContainText('22/23');
 await expect(comparison).toContainText('2024-06-30');
 await expect(comparison).toContainText('périmètre géographique historique');
 const table=comparison.getByRole('table');
 await expect(table.getByRole('row',{name:/^Inscrits/})).toContainText('832');
 await expect(table.getByRole('row',{name:/^Inscrits/})).toContainText('853');
 await expect(table.getByRole('row',{name:/^Votants/})).toContainText('530');
 await expect(table.getByRole('row',{name:/^Votants/})).toContainText('580');
 await expect(table.getByRole('row',{name:/^Participation/})).toContainText('63,7 %');
 await expect(table.getByRole('row',{name:/^Participation/})).toContainText('68,0 %');
 await expect(table.getByRole('row',{name:/^Participation/})).toContainText('+4,3 points');
 await expect(table.getByRole('row',{name:/^Abstention /})).toContainText('-4,3 points');
 await expect(page.locator('#bureau-comparison-b option[value="33114-2"]')).toHaveCount(0);
 await expect(comparison.getByRole('link')).toHaveAttribute('href',/data\.gouv\.fr/);
 const [download]=await Promise.all([page.waitForEvent('download'),comparison.getByRole('button',{name:'Exporter ces deux bureaux (CSV)'}).click()]);
 const csv=await readFile(await download.path(),'utf8');
 expect(download.suggestedFilename()).toBe('comparaison-bureaux-33067-1-33067-2.csv');
 const lines=csv.replace(/^\uFEFF/,'').split('\r\n');
 const fields=lines[0].split(';'),values=lines[1].split(';');
 const exported=Object.fromEntries(fields.map((key,index)=>[key,values[index]]));
 expect(exported.bureau_a).toBe('33067-1');expect(exported.bureau_b).toBe('33067-2');
 expect(exported.inscrits_a).toBe('832');expect(exported.inscrits_b).toBe('853');
 expect(exported.votants_a).toBe('530');expect(exported.votants_b).toBe('580');
 expect(Number(exported.ecart_participation_points)).toBeCloseTo(4.293387591306697,12);
 expect(exported.source).toContain('data.gouv.fr/datasets/');
 expect(exported.date_scrutin).toBe('2024-06-30');expect(exported.couverture).toBe('22/23');
 await comparison.scrollIntoViewIfNeeded();
 await mkdir('test-results/captures',{recursive:true});
 await comparison.screenshot({path:'test-results/captures/bureau-comparison-'+testInfo.project.name+'.png'});
 await page.locator('#bureau-commune').selectOption('Cavignac');
 await page.locator('#map-scope-value').selectOption('33114-2');
 await expect(comparison).toContainText('aucun résultat officiel apparié');
 await expect(comparison.getByRole('table')).toHaveCount(0);
 await expect(page.locator('#bureau-comparison-b')).toBeDisabled();
 await expect(comparison.getByRole('button',{name:'Exporter ces deux bureaux (CSV)'})).toHaveCount(0);
});

