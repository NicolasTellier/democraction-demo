import {test,expect} from '@playwright/test';import {mkdir,readFile} from 'node:fs/promises';
test.use({serviceWorkers:'block'});
test('listes fictives : choix, mesure, inversion, absence et cadre mobile',async({page},info)=>{
 test.skip(!['desktop','iphone'].includes(info.project.name));
 await page.goto('/');await page.locator('button[data-nav="analyse"]:visible').first().click();
 const root=page.locator('synthetic-list-comparison');
 const pick=(field,value)=>root.locator('[data-list-field="'+field+'"]').selectOption(value);
 await expect(root).toContainText('Choisissez explicitement');
 await pick('listAId','a-1');await pick('listBId','b-2');
 await expect(root.locator('tbody tr').first()).toContainText('+70');
 const exportCsv=async()=>{const [d]=await Promise.all([page.waitForEvent('download'),root.locator('[data-list-export]').click()]);expect(d.suggestedFilename()).toBe('comparaison-listes-fictives.csv');return readFile(await d.path(),'utf8');};
 const votesCsv=await exportCsv();expect(votesCsv).toContain('voix_a;exprimes_a;part_exprimes_a');
 expect(votesCsv).toContain(';votes;voix;B − A;');
 await pick('metric','share');
 await expect(root.locator('tbody tr').first()).toContainText('+15');
 await expect(root).toContainText('Aucun exprimé');
 await expect(root).toContainText('Résultat ou liste indisponible');
 await expect(root).toContainText('1/3 comparaisons disponibles');
 const shareCsv=await exportCsv();expect(shareCsv).toContain('zero-denominator');expect(shareCsv).toContain('missing-result');
 expect(shareCsv).toContain('Jeu de démonstration fictif A');expect(shareCsv).toContain('2026-11-20');
 await pick('firstId','b');
 await expect(root).toContainText('Choisissez explicitement');
 await pick('listAId','b-2');await pick('listBId','a-1');
 await expect(root.locator('tbody tr').first()).toContainText('-15');
 await root.locator('[data-list-code="33003"]').uncheck();
 await expect(root).toContainText('1/2 comparaisons disponibles');
 await expect(root).toContainText('2026-11-20');
 const finalCsv=await exportCsv();
 const lines=finalCsv.replace(/^\uFEFF/,'').split('\r\n');
 const fields=lines[0].split(';');expect(lines).toHaveLength(3);
 const row=Object.fromEntries(lines[1].split(';').map((value,i)=>[fields[i],value]));
 expect(row.code_insee).toBe('33001');expect(row.liste_a).toBe('b-2');expect(row.liste_b).toBe('a-1');
 expect(Number(row.ecart_b_moins_a.replace(/^'/,''))).toBe(-15);
 await root.locator('[data-list-code="33001"]').uncheck();await root.locator('[data-list-code="33002"]').uncheck();
 await expect(root.locator('[data-list-export]')).toHaveCount(0);
 await root.locator('[data-list-code="33001"]').check();await root.locator('[data-list-code="33002"]').check();
 await root.scrollIntoViewIfNeeded();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await mkdir('test-results/captures',{recursive:true});
 await root.locator('.tablewrap').evaluate(e=>e.scrollIntoView({block:'center'}));
 await page.screenshot({path:'test-results/captures/listes-fictives-'+info.project.name+'.png'});
});

test('vues fictives : sauvegarde, rappel, refus périmé et suppression persistante',async({page},info)=>{
 test.skip(!['desktop','iphone'].includes(info.project.name));
 const key='democraction-demo-synthetic-list-views';
 await page.goto('/');const nav=()=>page.locator('button[data-nav="analyse"]:visible').first().click();await nav();
 const root=page.locator('synthetic-list-comparison'),pick=(f,v)=>root.locator('[data-list-field="'+f+'"]').selectOption(v);
 await page.evaluate(()=>localStorage.setItem('democraction-demo-comparison-views','[]'));
 await pick('listAId','a-1');await pick('listBId','b-2');await pick('metric','share');
 await root.locator('[data-list-code="33003"]').uncheck();
 await root.locator('[data-list-save]').click();
 await expect(root.locator('.synthetic-saved-list li')).toHaveCount(1);
 await root.locator('[data-list-save]').click();await expect(root.locator('.synthetic-saved-notice')).toContainText('déjà enregistrée');
 await page.reload();await nav();
 await root.locator('[data-list-open]').click();
 await expect(root.locator('[data-list-field="listAId"]')).toHaveValue('a-1');
 await expect(root.locator('[data-list-field="listBId"]')).toHaveValue('b-2');
 await expect(root.locator('[data-list-field="metric"]')).toHaveValue('share');
 await expect(root.locator('[data-list-code]:checked')).toHaveCount(2);
 await expect(root.locator('tbody tr').first()).toContainText('+15');
 expect(await page.evaluate(()=>localStorage.getItem('democraction-demo-comparison-views'))).toBe('[]');
 const stored=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key);
 expect(Object.keys(stored[0]).sort()).toEqual(['datasetId','id','params','savedAt','version']);
 expect(Object.keys(stored[0].params).sort()).toEqual(['codes','firstId','listAId','listBId','metric','secondId']);
 await mkdir('test-results/captures',{recursive:true});
 await root.locator('.synthetic-saved-list').evaluate(e=>e.scrollIntoView({block:'center'}));
 await page.screenshot({path:'test-results/captures/listes-fictives-sauvegardees-'+info.project.name+'.png'});
 await page.evaluate(key=>{const views=JSON.parse(localStorage.getItem(key));views[0].params.listBId='liste-retiree';localStorage.setItem(key,JSON.stringify(views));},key);
 await page.reload();await nav();
 await root.locator('[data-list-open]').click();
 await expect(root.locator('.synthetic-saved-notice')).toContainText('Référence fictive périmée');
 await expect(root.locator('[data-list-field="listAId"]')).toHaveValue('');
 await expect(root.locator('[data-list-field="listBId"]')).toHaveValue('');
 await root.locator('.synthetic-saved-notice').evaluate(e=>e.scrollIntoView({block:'center'}));
 await page.screenshot({path:'test-results/captures/listes-fictives-perimees-'+info.project.name+'.png'});
 await root.locator('[data-list-delete]').click();await page.reload();await nav();
 await expect(root.locator('[data-list-open]')).toHaveCount(0);
 expect(await page.evaluate(key=>localStorage.getItem(key),key)).toBe('[]');
 expect(await page.evaluate(()=>localStorage.getItem('democraction-demo-comparison-views'))).toBe('[]');
 await pick('listAId','a-1');await pick('listBId','b-2');
 await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new DOMException('Recette : stockage plein','QuotaExceededError');};});
 await root.locator('[data-list-save]').click();
 await expect(root.locator('.synthetic-saved-notice')).toContainText('stockage plein');
 await expect(root.locator('[data-list-open]')).toHaveCount(0);
 expect(await page.evaluate(key=>localStorage.getItem(key),key)).toBe('[]');
});
