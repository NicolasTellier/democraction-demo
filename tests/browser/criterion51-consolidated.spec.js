import {test,expect} from '@playwright/test';
import {readFile,mkdir} from 'node:fs/promises';
test.use({serviceWorkers:'block'});
const KEY='democraction-demo-comparison-views';
test('comparaisons consolidées : sélection, vues, référence périmée, cartes, bureaux et CSV',async({page},info)=>{
 test.skip(!['desktop','iphone'].includes(info.project.name));test.setTimeout(120000);
 const fixture=JSON.parse(await readFile(new URL('../../data/resultats-bureaux-officiels-2024.json',import.meta.url),'utf8'));
 for(const scrutin of fixture.scrutins)for(const bureau of scrutin.bureaux)bureau.candidats=[{name:'Liste fictive',nuance:'TEST',votes:bureau.exprimes}];
 await page.route('**/data/resultats-bureaux-officiels-2024.json*',route=>route.fulfill({json:fixture}));
 const nav=async tab=>page.locator('button[data-nav="'+tab+'"]:visible').first().click();
 const capture=async(name,target)=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await target.evaluate(e=>e.scrollIntoView({block:'center',behavior:'instant'}));
  await mkdir('test-results/captures',{recursive:true});
  await page.screenshot({path:'test-results/captures/criterion51-'+name+'-'+info.project.name+'.png'});
 };
 await page.goto('/');await nav('analyse');
 await page.locator('#election-type').selectOption('muni');await page.locator('#election-tour').selectOption('t1');
 await page.locator('#analysis-ballot-a').selectOption('2020_muni_t1');
 await page.locator('#analysis-ballot-b').selectOption('2026_muni_t1');
 for(const value of ['33001','33366'])await page.locator('input[name="analysis-commune"][value="'+value+'"]').check();
 const table=page.getByRole('table',{name:'Effectifs et taux exacts par commune'});
 await expect(table.locator('tbody tr')).toHaveCount(2);
 await expect(table).toContainText('Écart B − A');
 const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'Exporter cette comparaison (CSV)'}).click()]);
 const csv=await readFile(await download.path(),'utf8');
 expect(csv).toContain('33001;Municipales 2020 — tour 1;1515;713;');
 expect(csv).toContain('data.gouv.fr / ministère de l’Intérieur');
 expect(csv).toContain('2026-07-07');
 await page.getByRole('button',{name:'Enregistrer cette comparaison',exact:true}).click();
 await expect(page.locator('.comparison-saved-list li')).toHaveCount(1);
 await expect(page.locator('.comparison-saved-list')).toContainText('mise à jour 2026-07-07');
 await page.locator('input[name="analysis-commune"][value="33001"]').uncheck();
 await page.reload();await nav('analyse');
 await expect(page.locator('input[name="analysis-commune"]:checked')).toHaveCount(1);
 await page.locator('.comparison-saved-list').getByRole('button',{name:'Ouvrir',exact:true}).click();
 await expect(page.locator('input[name="analysis-commune"]:checked')).toHaveCount(2);
 await expect(page.locator('#analysis-ballot-a')).toHaveValue('2020_muni_t1');
 await expect(page.locator('#analysis-ballot-b')).toHaveValue('2026_muni_t1');
 if(info.project.name==='iphone')await table.evaluate(t=>{t.parentElement.scrollLeft=t.parentElement.scrollWidth;});
 await capture('vue-rouverte',table.locator('..'));
 await page.evaluate(key=>{const views=JSON.parse(localStorage.getItem(key));views[0].ballotB='scrutin-retire';localStorage.setItem(key,JSON.stringify(views));},KEY);
 await page.reload();await nav('analyse');
 await page.locator('.comparison-saved-list').getByRole('button',{name:'Ouvrir',exact:true}).click();
 await expect(page.locator('.notice[role=status]')).toContainText('ne figure plus dans les données disponibles');
 await expect(page.locator('#analysis-ballot-b')).toHaveValue('2026_muni_t1');
 await capture('reference-perimee',page.locator('.notice[role=status]'));
 await page.locator('.comparison-saved-list').getByRole('button',{name:'Supprimer',exact:true}).click();
 await page.reload();await nav('analyse');
 await expect(page.getByText('Aucune comparaison enregistrée sur cet appareil.')).toBeVisible();
 await nav('carte');
 await page.locator('#map-scope').selectOption('epci');
 await page.locator('#map-scope-value').selectOption({index:1});
 await expect.poll(async()=>page.locator('#map [data-commune-code][stroke-width="3"]').count()).toBeGreaterThan(1);
 await page.locator('[data-map-mode="compare"]').click();
 await page.locator('#compare-left').selectOption('2020_muni_t1');
 await page.locator('#compare-right').selectOption('2026_muni_t1');
 await expect(page.locator('.map-compare-table strong')).toContainText('Écarts A − B');
 const abzac=page.locator('.map-compare-table tbody tr').filter({has:page.getByRole('cell',{name:'Abzac',exact:true})});
 await expect(abzac.locator('td').last()).toHaveText('-11.6');
 await expect(page.locator('#map-left .map-legend')).toContainText('Participation électorale');
 await expect(page.locator('#map-right .map-legend')).toContainText('Participation électorale');
 await capture('deux-cartes',page.locator('#map-left'));
 await page.locator('[data-map-mode="explore"]').click();
 await page.locator('#map-scope').selectOption('bureau');
 await page.locator('#bureau-commune').selectOption('Bourg');
 await page.locator('#map-scope-value').selectOption('33067-1');
 await page.locator('#bureau-comparison-b').selectOption('33067-2');
 const bureau=page.locator('.official-bureau-comparison');
 await expect(bureau).toContainText('22/23');await expect(bureau).toContainText('2024-06-30');
 await expect(bureau).toContainText('périmètre géographique historique');
 await expect(bureau.getByRole('row',{name:/^Participation/})).toContainText('+4,3 points');
 const [bd]=await Promise.all([page.waitForEvent('download'),bureau.getByRole('button',{name:'Exporter ces deux bureaux (CSV)'}).click()]);
 const lines=(await readFile(await bd.path(),'utf8')).replace(/^\uFEFF/,'').split('\r\n');
 const exported=Object.fromEntries(lines[0].split(';').map((key,index)=>[key,lines[1].split(';')[index]]));
 expect(exported.bureau_a).toBe('33067-1');expect(exported.bureau_b).toBe('33067-2');
 expect(Number(exported.ecart_participation_points)).toBeCloseTo(4.293387591306697,12);
 expect(exported.source).toContain('data.gouv.fr/datasets/');expect(exported.date_scrutin).toBe('2024-06-30');
 await capture('bureaux',bureau);
 await page.locator('#bureau-commune').selectOption('Cavignac');await page.locator('#map-scope-value').selectOption('33114-2');
 await expect(bureau).toContainText('aucun résultat officiel apparié');
 await expect(bureau.getByRole('table')).toHaveCount(0);
 await expect(page.locator('#bureau-comparison-b')).toBeDisabled();
 await expect(bureau.getByRole('button',{name:'Exporter ces deux bureaux (CSV)'})).toHaveCount(0);
});
