import {test,expect} from '@playwright/test';
import {readFile,mkdir} from 'node:fs/promises';
test.use({serviceWorkers:'block'});
const REAL='democraction-demo-comparison-views',FAKE='democraction-demo-synthetic-list-views';
test('comparaisons intégrées : participation, listes fictives, CSV et limites des filtres globaux',async({page},info)=>{
 test.skip(!['desktop','iphone'].includes(info.project.name));test.setTimeout(120000);
 const nav=tab=>page.locator('button[data-nav="'+tab+'"]:visible').first().click();
 const capture=async(name,target)=>{
  await page.emulateMedia({reducedMotion:'reduce'});await target.evaluate(e=>e.scrollIntoView({block:'center',behavior:'instant'}));
  await mkdir('test-results/captures',{recursive:true});
  await page.screenshot({path:'test-results/captures/comparaisons-integrees-'+name+'-'+info.project.name+'.png'});
 };
 const download=async(button)=>{const[d]=await Promise.all([page.waitForEvent('download'),button.click()]);return readFile(await d.path(),'utf8');};
 await page.goto('/');await nav('analyse');
 await page.locator('#election-type').selectOption('muni');await page.locator('#election-tour').selectOption('t1');
 await page.locator('#analysis-ballot-a').selectOption('2020_muni_t1');await page.locator('#analysis-ballot-b').selectOption('2026_muni_t1');
 for(const code of ['33001','33366'])await page.locator('input[name="analysis-commune"][value="'+code+'"]').check();
 const real=page.getByRole('table',{name:'Effectifs et taux exacts par commune'});
 await expect(real.locator('tbody tr')).toHaveCount(2);
 await expect(real).toContainText('Abstention A');await expect(real).toContainText('+11,6 points');
 const realCsv=await download(page.getByRole('button',{name:'Exporter cette comparaison (CSV)',exact:true}));
 expect(realCsv).toContain('33001;Municipales 2020 — tour 1;1515;713;');
 await page.getByRole('button',{name:'Enregistrer cette comparaison',exact:true}).click();
 const root=page.locator('synthetic-list-comparison');
 const pick=(f,v)=>root.locator('[data-list-field="'+f+'"]').selectOption(v);
 await pick('listAId','a-1');await pick('listBId','b-2');
 await expect(root.locator('tbody tr').first()).toContainText('+70');
 await pick('metric','share');await root.locator('[data-list-code="33003"]').uncheck();
 await expect(root.locator('tbody tr').first()).toContainText('+15');
 await root.locator('[data-list-save]').click();
 const before=await page.evaluate(([a,b])=>[localStorage.getItem(a),localStorage.getItem(b)],[REAL,FAKE]);
 expect(JSON.parse(before[0])).toHaveLength(1);expect(JSON.parse(before[1])).toHaveLength(1);
 await page.locator('#filter-commune').selectOption('Saint-André-de-Cubzac');
 await page.locator('#election-type').selectOption('pres');await page.locator('#election-year').selectOption('2022');
 await root.locator('[data-list-open]').click();
 // Contre-exemple documenté : le jeu fictif n'est pas filtré par la commune ou le scrutin réels.
 await expect(page.locator('input[name="analysis-commune"]')).toHaveCount(1);
 await expect(page.locator('input[name="analysis-commune"]')).toHaveValue('33366');
 await expect(root.locator('[data-list-code]')).toHaveCount(3);
 await expect(root.locator('[data-list-code="33001"]')).toBeChecked();
 await expect(root.locator('[data-list-field="firstId"]')).toHaveValue('a');
 await expect(root.locator('[data-list-field="firstId"] option:checked')).toContainText('Municipales 2020');
 await expect(root).toContainText('indépendant des filtres géographiques');
 const fakeCsv=await download(root.locator('[data-list-export]'));
 const lines=fakeCsv.replace(/^\uFEFF/,'').split('\r\n'),fields=lines[0].split(';');
 const record=Object.fromEntries(lines[1].split(';').map((value,i)=>[fields[i],value]));
 expect(lines).toHaveLength(3);expect(record.synthetic).toBe('true');expect(record.scrutin_a).toBe('a');
 expect(record.liste_a).toBe('a-1');expect(record.liste_b).toBe('b-2');expect(record.ecart_b_moins_a).toBe('15');
 expect(record.date_source_a).toBe('2026-11-20');
 await capture('choix-fictifs',root.locator('[data-list-field="firstId"]'));
 await page.reload();await nav('analyse');await root.locator('[data-list-open]').click();
 await expect(page.locator('#filter-commune')).toHaveValue('Saint-André-de-Cubzac');
 await expect(page.locator('#election-type')).toHaveValue('pres');
 await expect(root.locator('[data-list-field="metric"]')).toHaveValue('share');
 await expect(root.locator('tbody tr').first()).toContainText('+15');
 // Montrer réellement les commandes de la liste enregistrée, même sur un petit écran.
 await capture('vue-fictive',root.locator('[data-list-open]'));
 await expect(root.locator('[data-list-open]')).toBeInViewport();
 await page.locator('.comparison-saved-list').getByRole('button',{name:'Ouvrir',exact:true}).click();
 await expect(page.locator('#filter-commune')).toHaveValue('');
 await expect(page.locator('#election-type')).toHaveValue('muni');
 await expect(page.locator('#election-year')).toHaveValue('');
 await expect(page.locator('input[name="analysis-commune"]:checked')).toHaveCount(2);
 expect(await page.evaluate(key=>localStorage.getItem(key),FAKE)).toBe(before[1]);
 await root.locator('[data-list-open]').click();await root.locator('[data-list-delete]').click();
 expect(await page.evaluate(key=>localStorage.getItem(key),REAL)).toBe(before[0]);
 await page.locator('.comparison-saved-list').getByRole('button',{name:'Supprimer',exact:true}).click();
 await page.reload();await nav('analyse');
 await expect(root.locator('[data-list-open]')).toHaveCount(0);
 await expect(page.locator('.comparison-saved-list li')).toHaveCount(0);
 expect(await page.evaluate(([a,b])=>[localStorage.getItem(a),localStorage.getItem(b)],[REAL,FAKE])).toEqual(['[]','[]']);
});
